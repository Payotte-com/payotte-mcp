var DMTO = dmto_default;
var arrondi = (n) => Math.round(n);
function emoluments(prix) {
  let reste = prix, bas = 0, ht = 0;
  for (const t of fraisNotaire_default.emoluments.tranches) {
    const haut = t.jusqua ?? Infinity;
    const part = Math.max(0, Math.min(prix, haut) - bas);
    ht += part * t.taux / 100;
    bas = haut;
    reste -= part;
    if (reste <= 0) break;
  }
  const tva = ht * fraisNotaire_default.emoluments.tva / 100;
  return { ht: arrondi(ht), tva: arrondi(tva), ttc: arrondi(ht + tva) };
}
function fraisAncien(prix, departement, primoAccedant = false) {
  const tauxDep = primoAccedant ? departement.tauxBase : departement.tauxHorsPrimo;
  const dep = arrondi(prix * tauxDep / 100);
  const com = arrondi(prix * fraisNotaire_default.taxeCommunale.taux / 100);
  const assiette = arrondi(dep * fraisNotaire_default.fraisAssiette.taux / 100);
  const csi = Math.max(fraisNotaire_default.securiteImmobiliere.minimum, arrondi(prix * fraisNotaire_default.securiteImmobiliere.taux / 100));
  const e = emoluments(prix);
  const total = dep + com + assiette + csi + e.ttc;
  return {
    prix,
    departement,
    primoAccedant,
    tauxDepartemental: tauxDep,
    droitsDepartementaux: dep,
    taxeCommunale: com,
    fraisAssiette: assiette,
    droitsMutation: dep + com + assiette,
    securiteImmobiliere: csi,
    emolumentsHT: e.ht,
    emolumentsTVA: e.tva,
    emolumentsTTC: e.ttc,
    total,
    pourcentage: Math.round(total / prix * 1e4) / 100,
    // Abattement ou taux réduit propre au département (ex. Calvados, Savoie) : non calculé, signalé.
    casParticulier: departement.autresTaux.length > 0 || departement.abattements.length > 0
  };
}
function departementParCode(code) {
  const c = code === "2A" || code === "2B" ? "20" : code;
  return DMTO.departements.find((d) => d.codes.includes(c));
}
function urlDepartement(d) {
  const s = d.nom.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  return `/france/departements/${d.code.replace("/", "-")}-${s}`;
}

