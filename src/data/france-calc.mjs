var c2 = (n) => Math.round(n * 100) / 100;
function emolumentsHT(assiette) {
  let bas = 0, ht = 0;
  for (const t of frais_notaire_neuf_default.emoluments.tranches) {
    const haut = t.jusqua ?? Infinity;
    ht += Math.max(0, Math.min(assiette, haut) - bas) * t.taux / 100;
    bas = haut;
    if (assiette <= haut) break;
  }
  return c2(ht);
}
function fraisNeuf(e) {
  const assiette = e.assiette ?? (e.tvaMentionneeDistinctement ? c2(e.prixTTC / (1 + (e.tauxTVA ?? frais_notaire_neuf_default.tva.valeur) / 100)) : e.prixTTC);
  const tpf = c2(assiette * frais_notaire_neuf_default.tauxTaxePubliciteFonciere.valeur / 100);
  const fa = c2(tpf * frais_notaire_neuf_default.fraisAssiette.valeur / 100);
  const csi = c2(Math.max(frais_notaire_neuf_default.contributionSecuriteImmobiliere.minimum, assiette * frais_notaire_neuf_default.contributionSecuriteImmobiliere.valeur / 100));
  const eHT = emolumentsHT(assiette), eTVA = c2(eHT * frais_notaire_neuf_default.emoluments.tva / 100);
  const total = c2(tpf + fa + csi + eHT + eTVA);
  return { assiette, taxePubliciteFonciere: tpf, fraisAssiette: fa, droits: c2(tpf + fa), csi, emolumentsHT: eHT, tvaEmoluments: eTVA, emolumentsTTC: c2(eHT + eTVA), totalReglemente: total, pourcentDuPrixTTC: c2(total / (e.prixTTC ?? assiette) * 100) };
}
